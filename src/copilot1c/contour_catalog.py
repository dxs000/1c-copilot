def seed(conn, project: str) -> dict[str, int]:
    """Заводит системы и подсистемы каталога; существующие пункты не трогает, только дополняет псевдонимы.
    Повторный запуск безопасен."""
    from copilot1c.contours import ContourRegistry, _clean_aliases

    reg = ContourRegistry(conn, project)
    out = {"systems": 0, "subsystems": 0, "aliases": 0}

    def find(kind: str, name: str, parent: int | None) -> dict | None:
        return next((c for c in reg.list(include_inactive=True) if c["kind"] == kind and c["parent_id"] == parent
                     and c["name"].casefold() == name.casefold()), None)

    def ensure(kind: str, name: str, aliases: list[str], parent: int | None, notes: str | None, counter: str) -> int:
        c = find(kind, name, parent)
        if c is None:
            c = reg.create({"kind": kind, "name": name, "aliases": aliases, "parent_id": parent, "notes": notes})
            out[counter] += 1
            return c["id"]
        merged = _clean_aliases([*c["aliases"], *aliases])
        if len(merged) > len(c["aliases"]):
            reg.update(c["id"], {"aliases": merged})
            out["aliases"] += len(merged) - len(c["aliases"])
        return c["id"]

    for name, aliases, notes, subs in CATALOG:
        sid = ensure("system", name, aliases, None, notes, "systems")
        for sub, sub_aliases in subs:
            ensure("subsystem", sub, sub_aliases, sid, None, "subsystems")
    return out
